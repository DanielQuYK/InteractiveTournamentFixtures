/*
* Boys B Grade group-stage schedules. The organisers have published fixtures only: no game has been played and
* no final-round bracket exists yet, so each competition has no knockout matches. Dates are dd-mm-yy.
*/

/** B Grade competitions share one shape: fixtures only, nothing played, no bracket published. */
function boysB(id: string, a: string, level: string, region: string, shortName: string, name: string, groupsRaw: string): DivisionConfig {
  const rows = groupsRaw.trim().split('\n').map((l) => l.split('|'))
  const groups = new Set(rows.map((r) => r[0])).size
  const teams = new Set(rows.flatMap((r) => [r[4], r[5]])).size
  return {
    id,
    grade: 'B',
    level,
    region,
    shortName,
    title: `${name} · Boys B Grade`,
    blurb: `${groups} groups · ${teams} teams · fixtures published, no games played yet`,
    documentDate: '',
    asOf: '',
    groupsRaw,
    withdrawn: {},
    penalties: {},
    firstRoundName: 'First round',
    lineupConfirmed: false,
    results: NO_RESULTS,
    koMatches: [],
  }
}

